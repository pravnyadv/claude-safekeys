for (const [command, web, ssh] of scenarios) {
  test(`destinations: ${command}`, () => {
    const actual = destinationsOf(command)
    expect(actual.web.sort()).toEqual([...web].sort())
    expect(actual.ssh.sort()).toEqual([...ssh].sort())
  })
}
